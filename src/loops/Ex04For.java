package loops;

public class Ex04For {
    static void main (String[] args) {

        // variável de controle
        int i;
        int soma = 0;

        // loop for
        for (i = 1; i <= 5; i++) {
            soma = soma + i;
        }

        System.out.println(soma);

        // Pseudocódigo
        // for (variável inicial; limitador; faça isso)
        //      escreva a variável inicial
        // fim

    }
}
