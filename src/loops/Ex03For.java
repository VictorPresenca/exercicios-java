package loops;

public class Ex03For {
    static void main(String[] args) {

        // variável de controle
        int j;

        // loop for
        for (j = 1; j <= 5; j++){
            System.out.println("Java " + j);
        }

        // mensagem de finalização
        System.out.println("Fim da sequência");

    }
}
