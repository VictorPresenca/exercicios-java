package loops;

public class Ex01For {
    static void main(String[] args) {

        // variável de controle
        int number;

        // loop estrutura 'for'
        for (number = 0; number <=10; number++) {
            System.out.println(number);
        }

        // Pseudocódigo
        // for (variável inicial; limitador; faça isso)
        //      escreva a variável inicial
        // fim

        // aviso de fim de contage
        System.out.println("final da contagem");
    }
}
