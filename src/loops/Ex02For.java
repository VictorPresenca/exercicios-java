package loops;

public class Ex02For {
    static void main(String[] args) {

        // variável de controle
        int number;

        // loop em estrutura 'for'
        for (number = 10; number >= 0; number--) {
            System.out.println(number);
        }

        // pseudocódigo 
        // for (variável inicial; limite; faça isso)
        //      escreva (variável inicial)
        // fim

        // aviso de final de contagem
        System.out.println("fim da contagem decrescente");

    }
}
