package loops;

public class Ex05While {
    static void main(String[] args) {

        // variável de controle
        int contador = 1;

        // loop estrutura do while
        do {
            System.out.println(contador);
            ++contador;
        }while (contador <= 10);

        // pseudocódigo
        // faça {
        //      escreva a variável
        //      acrescente +1 na variável
        // } enquanto (variável for menor ou igual à 10);

    }
}
